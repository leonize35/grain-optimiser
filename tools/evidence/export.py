# ---------------------------------------------------------------- statistics
def t_pdf(x: float, df: int) -> float:
    c = math.gamma((df + 1) / 2) / (math.sqrt(df * math.pi) * math.gamma(df / 2))
    return c * (1 + x * x / df) ** (-(df + 1) / 2)


def t_two_sided_p(t: float, df: int) -> float:
    """Two-sided p-value, by Simpson integration of the Student t density from 0 to |t|."""
    a = abs(t)
    if a == 0:
        return 1.0
    if a > 200:
        return 0.0
    n = 4000
    h = a / n
    s = t_pdf(0, df) + t_pdf(a, df) + sum((4 if i % 2 else 2) * t_pdf(i * h, df) for i in range(1, n))
    return max(0.0, min(1.0, 1 - 2 * s * h / 3))


def holm(pvalues: list[float | None]) -> list[float | None]:
    idx = sorted((p, i) for i, p in enumerate(pvalues) if p is not None)
    m, out, running = len(idx), [None] * len(pvalues), 0.0
    for rank, (p, i) in enumerate(idx):
        running = max(running, min(1.0, (m - rank) * p))
        out[i] = running
    return out


def summarise(values: list[float | None]) -> dict:
    i = ci(values)
    return {"n": i.n, "mean": i.mean, "sd": i.sd, "ci_low": i.low, "ci_high": i.high, "half_width": i.half_width}


# ---------------------------------------------------------------- io
def write_csv(path: Path, rows: list[dict]) -> None:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0]), lineterminator="\n")
    w.writeheader()
    for r in rows:
        w.writerow({k: (f"{v:.6g}" if isinstance(v, float) else v) for k, v in r.items()})
    path.write_text(buf.getvalue(), encoding="utf-8")


def f(x, d=1):
    return "–" if x is None else f"{x:.{d}f}"


