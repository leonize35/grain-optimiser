def _interval(p):
    from silo_engine.experiments.runner import Interval
    return Interval(p["n"], p["mean"], p["sd"], p["half_width"])


def paired_figure(path: Path, rows: list[dict]) -> None:
    """Dot-and-whisker chart of paired differences with a zero line; one axis (minutes)."""
    W, H, L, R, T, B = 720, 360, 190, 24, 70, 50
    pw, ph = W - L - R, H - T - B
    lo = min(min(c["ci_low"] for c in rows if c["ci_low"] is not None), 0)
    hi = max(max(c["ci_high"] for c in rows if c["ci_high"] is not None), 0)
    pad = (hi - lo) * 0.08
    lo, hi = lo - pad, hi + pad
    x = lambda v: L + pw * (v - lo) / (hi - lo)  # noqa: E731
    step = next(m * 10 ** k for k in range(0, 4) for m in (1, 2, 5) if (hi - lo) / (m * 10 ** k) <= 8)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="Inter, Helvetica, Arial, sans-serif">',
           f'<rect width="{W}" height="{H}" fill="{SURFACE}"/>',
           f'<text x="24" y="26" font-size="16" font-weight="600" fill="{INK}">Paired difference in mean unloading turnaround</text>',
           f'<text x="24" y="46" font-size="12" fill="{INK2}">EV-C1, demand ×1.0, n = 5 seed pairs; dot: mean difference; whisker: 95% CI; filled: Holm-adjusted p &lt; 0.05. Synthetic.</text>']
    t = math.ceil(lo / step) * step
    while t <= hi:
        out.append(f'<line x1="{x(t):.1f}" x2="{x(t):.1f}" y1="{T}" y2="{T + ph}" stroke="{GRID}" stroke-width="1"/>')
        out.append(f'<text x="{x(t):.1f}" y="{T + ph + 16}" font-size="11" fill="{INK2}" text-anchor="middle">{t:g}</text>')
        t += step
    out.append(f'<line x1="{x(0):.1f}" x2="{x(0):.1f}" y1="{T}" y2="{T + ph}" stroke="{INK2}" stroke-width="1.5"/>')
    out.append(f'<text x="{L + pw / 2}" y="{H - 10}" font-size="11" fill="{INK2}" text-anchor="middle">Difference in mean turnaround (min), second mapping minus first</text>')
    rowh = ph / len(rows)
    colour = {"M-PT - M-FF": SERIES[1], "M-SF - M-FF": SERIES[2], "M-SF - M-PT": SERIES[0]}
    for k, c in enumerate(rows):
        y = T + rowh * (k + 0.5)
        out.append(f'<text x="{L - 10}" y="{y + 4:.1f}" font-size="11" fill="{INK}" text-anchor="end">Site {c["site"]}: {c["comparison"]}</text>')
        if c["identical_decisions"]:
            out.append(f'<text x="{x(0) + 8:.1f}" y="{y + 4:.1f}" font-size="11" fill="{INK2}">identical decisions (0)</text>')
            continue
        col = colour[c["comparison"]]
        filled = c["support"].startswith("supported")
        out.append(f'<line x1="{x(c["ci_low"]):.1f}" x2="{x(c["ci_high"]):.1f}" y1="{y:.1f}" y2="{y:.1f}" stroke="{col}" stroke-width="2"/>')
        out.append(f'<circle cx="{x(c["mean_difference"]):.1f}" cy="{y:.1f}" r="5" fill="{col if filled else SURFACE}" stroke="{col}" stroke-width="2">'
                   f'<title>Site {c["site"]}, {c["comparison"]}: {c["mean_difference"]:.1f} min [{c["ci_low"]:.1f}, {c["ci_high"]:.1f}], Holm p = {c["p_holm"]:.3f}</title></circle>')
    out.append("</svg>")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


