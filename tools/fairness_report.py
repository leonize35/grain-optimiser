"""Fairness and starvation baseline across independent replications (Q1 reporting; no fairness intervention).

Runs the prototype's demo Site A (tests/golden/validation_cases.json, `site_a_valid`; not customer data) with
generated arrivals and stochastic service times, under both dispatch policies and two demand levels, with the same
replication seeds (common random numbers) as `experiments.runner.run_experiment`. Writes a Markdown report.

Two views per commodity:
- across replications: the mean of each replication's figure, with a 95% confidence interval (t distribution);
- pooled: every truck of every replication together (mean, median, 95th percentile, maximum).
Waits of unfinished trucks are their waiting so far (lower bounds). Percentiles are nearest rank.

Usage:  python tools/fairness_report.py [--replications 20] [--out docs/audit/FAIRNESS_BASELINE.md]
"""
import argparse
import copy
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from silo_engine.config import load_site_config  # noqa: E402
from silo_engine.experiments.runner import ci, kpis_of  # noqa: E402
from silo_engine.inputs.generated import generate_arrivals  # noqa: E402
from silo_engine.sim.random_streams import derived_seed  # noqa: E402
from silo_engine.sim.service_times import StochasticServiceTimes  # noqa: E402
from silo_engine.sim.truck_flow import TruckFlowModel  # noqa: E402

BASE_SEED = 20261019  # run_experiment's default
POLICIES = ("strict_fifo", "feasible_first")
DEMAND = (1.0, 1.2)


def rank(xs: list[float], p: float) -> float | None:
    xs = sorted(xs)
    return xs[max(0, math.ceil(p * len(xs)) - 1)] if xs else None


def fmt(x: float | None, digits: int = 1) -> str:
    return "–" if x is None else f"{x:.{digits}f}"


def fmt_ci(values: list[float | None], digits: int = 1) -> str:
    i = ci(values)
    if i.mean is None:
        return "–"
    return f"{i.mean:.{digits}f}" + ("" if i.half_width is None else f" ± {i.half_width:.{digits}f}")


def run_arm(raw: dict, policy: str, factor: float, replications: int) -> dict:
    site = load_site_config(copy.deepcopy(raw))
    reps, pooled, failed = [], [], 0
    for i in range(replications):
        seed = derived_seed(BASE_SEED, "replication", i)
        r = TruckFlowModel(site, generate_arrivals(site, seed, days=1, demand_factor=factor),
                           StochasticServiceTimes(site, seed), policy=policy).run()
        if r.stall is not None or r.violations or r.material_balance_kg != 0:
            failed += 1  # excluded, as in run_experiment
            continue
        reps.append(kpis_of(r))
        pooled.extend(m for m in r.truck_metrics.values() if m.activity == "unload")
    return {"reps": reps, "pooled": pooled, "failed": failed}


def commodity_rows(arm: dict, commodities: list[str]) -> list[str]:
    rows = []
    for c in commodities:
        trucks = [m for m in arm["pooled"] if m.commodity == c]
        if not trucks:
            continue
        waits = [m.total_waiting_min for m in trucks]
        k = lambda name: [r.get(f"unload.{c}.{name}") for r in arm["reps"]]  # noqa: E731
        n = len(arm["reps"])
        rows.append(" | ".join([
            c, f"{len(trucks) / n:.1f}",
            fmt_ci(k("mean_total_wait_min")), fmt_ci(k("median_total_wait_min")), fmt_ci(k("p95_total_wait_min")),
            fmt_ci(k("max_total_wait_min")),
            fmt(sum(waits) / len(waits)), fmt(rank(waits, 0.5)), fmt(rank(waits, 0.95)), fmt(max(waits)),
            fmt_ci(k("mean_overtaken"), 2), str(max(m.overtaken_by_later for m in trucks)),
            f"{sum(m.starved for m in trucks) / len(trucks):.1%}", fmt_ci(k("starved")),
            fmt_ci(k("still_waiting")),
        ]))
    return rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--replications", type=int, default=20)
    ap.add_argument("--out", default=str(ROOT / "docs" / "audit" / "FAIRNESS_BASELINE.md"))
    args = ap.parse_args()
    cases = json.loads((ROOT / "tests" / "golden" / "validation_cases.json").read_text(encoding="utf-8"))["cases"]
    raw = next(c for c in cases if c["name"] == "site_a_valid")["config"]
    commodities = [c["id"] for c in raw["commodities"]]
    threshold = load_site_config(copy.deepcopy(raw)).fairness.starvation_wait_minutes

    lines = [
        "# Fairness and starvation baseline (prototype demo Site A)", "",
        "Generated by `python tools/fairness_report.py --replications "
        f"{args.replications}`. Reporting only: no overtaking limit or other fairness intervention is active.", "",
        f"- Site: prototype demo `site_a_valid` (not customer data); one day; generated arrivals; stochastic service "
        f"times; replication seeds `derived_seed({BASE_SEED}, 'replication', i)`, the same for every arm (common "
        "random numbers).",
        f"- Starvation threshold: {threshold:g} min total waiting (default reporting threshold); no overtake threshold.",
        "- *Across replications*: mean of each replication's figure ± 95% confidence half-width (t distribution).",
        "- *Pooled*: all unloading trucks of all replications together. Percentiles are nearest rank.",
        "- Waits of trucks still on site at the end of the day are their waiting so far (lower bounds).",
        "- Verification output only. These figures are not validated against any real silo.", "",
    ]
    header = ("| Commodity | Trucks / day | Mean wait | Median wait | P95 wait | Max wait | Pooled mean | Pooled median "
              "| Pooled P95 | Pooled max | Mean overtaken | Max overtaken | Starved (share) | Starved / day "
              "| Unfinished / day |")
    for factor in DEMAND:
        for policy in POLICIES:
            arm = run_arm(raw, policy, factor, args.replications)
            used = len(arm["reps"])
            k = lambda name: [r.get(name) for r in arm["reps"]]  # noqa: E731
            lines += [f"## Demand × {factor:g}, policy `{policy}`", "",
                      f"Replications used: {used} of {args.replications} (excluded: {arm['failed']}). "
                      f"Received: {fmt_ci(k('received_t'), 0)} t/day. Unloading trucks completed: "
                      f"{fmt_ci(k('unload.completed'))}/day; unfinished: {fmt_ci(k('unload.unfinished'))}/day; "
                      f"maximum overtakes of any truck: {fmt_ci(k('unload.max_overtaken'))}/day.", "",
                      "Waits are total waiting time on site, in minutes.", "",
                      header, "|" + "---|" * (header.count("|") - 1)]
            lines += [f"| {row} |" for row in commodity_rows(arm, commodities)]
            lines.append("")
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
